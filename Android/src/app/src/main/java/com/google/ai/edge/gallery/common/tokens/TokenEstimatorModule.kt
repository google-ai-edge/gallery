package com.google.ai.edge.gallery.common.tokens

import dagger.Binds
import dagger.Module
import dagger.hilt.InstallIn
import dagger.hilt.components.SingletonComponent
import javax.inject.Singleton

/** Hilt module binding [DefaultTokenEstimator] as the app-wide [TokenEstimator]. */
@Module
@InstallIn(SingletonComponent::class)
abstract class TokenEstimatorModule {

  @Binds
  @Singleton
  abstract fun bindTokenEstimator(estimator: DefaultTokenEstimator): TokenEstimator
}
